destatis_table <- function(tab, i) {
  new("actuarialtable", x = tab$x, lx = tab$Dx * 1.01^tab$x, interest = i)
}
men_1 <- destatis_table(men_1pc, 0.01)
women_1 <- destatis_table(women_1pc, 0.01)
women_5 <- destatis_table(women_1pc, 0.05)
men_5 <- destatis_table(men_1pc, 0.05)

# upper bound of the (unprinted) tail beyond age 100 at 5%, on the D scale
tail_upper_5pc <- function(tab) (tab$Nx[tab$x == 100] - tab$Dx[tab$x == 100]) * (1.01 / 1.05)^101

expect_in_bracket <- function(published, lower, upper, digits = 3) {
  half <- 0.5 * 10^(-digits) + 1e-9
  expect_gte(published, lower - half)
  expect_lte(published, upper + half)
}

test_that("Destatis 2002/2004: printed lx agree with lx rebuilt from Dx", {
  expect_lte(max(abs(men_1@lx - men_1pc$lx)), 0.5)
  expect_lte(max(abs(women_1@lx - women_1pc$lx)), 0.5)
})

test_that("Destatis 2002/2004 at 1%: Dx reproduced through pure endowments from age 0", {
  for (tab in list(list(men_1, men_1pc), list(women_1, women_1pc))) {
    D_pkg <- 1e5 * Exn(tab[[1]], x = 0, n = tab[[2]]$x)
    expect_lte(max(abs(D_pkg - tab[[2]]$Dx)), 1e-6)
  }
})

test_that("Destatis 2002/2004 at 1%: annuities-due a_x for every age, men and women", {
  for (tab in list(list(men_1, men_1pc), list(women_1, women_1pc))) {
    pub <- tab[[2]]
    N101 <- pub$Nx[pub$x == 100] - pub$Dx[pub$x == 100]
    a_pkg <- axn(tab[[1]], x = pub$x) + N101 / pub$Dx
    expect_lte(max(abs(a_pkg - pub$ax)), 0.0005 + 1e-6)
  }
})

test_that("Destatis 2002/2004 at 1%: temporary annuities from printed Nx", {
  pub <- men_1pc
  r <- function(a) pub[pub$x == a, ]
  # a_(40:25) = (N40 - N65) / D40
  expect_equal(axn(men_1, x = 40, n = 25), (r(40)$Nx - r(65)$Nx) / r(40)$Dx, tolerance = 1e-7)
  # deferred: 25|a_40 = N65 / D40 (whole life part beyond 100 from the printed tail)
  N101 <- r(100)$Nx - r(100)$Dx
  expect_equal(axn(men_1, x = 40, m = 25) + N101 / r(40)$Dx, r(65)$Nx / r(40)$Dx, tolerance = 1e-7)
})

test_that("Destatis example 3.3/3.4 (woman aged 70, 5%): tail-free values", {
  # D70 = 2.826,290 and D75 = 2.018,899 at 5%
  expect_equal(round(1e5 * Exn(women_5, x = 0, n = 70), 3), 2826.290)
  expect_equal(round(1e5 * Exn(women_5, x = 0, n = 75), 3), 2018.899)
  # 20-year temporary annuity-due 70-90: a = 10,410; annuity for 200.000 EUR = 19.212,30 EUR
  a7020 <- axn(women_5, x = 70, n = 20)
  expect_equal(round(a7020, 3), 10.410)
  expect_equal(round(200000 / round(a7020, 3), 2), 19212.30)
})

test_that("Destatis examples 3.1-3.3 (woman aged 70, 5%): whole life values in the tail bracket", {
  D70 <- 1e5 * Exn(women_5, x = 0, n = 70)
  up <- tail_upper_5pc(women_1pc) / D70
  a70 <- axn(women_5, x = 70)
  # a_70 = 10,853
  expect_in_bracket(10.853, a70, a70 + up)
  # monthly with the publication's deduction k(12) = 0,4664: 10,387
  expect_in_bracket(10.387, a70 - 0.4664, a70 + up - 0.4664)
  # 5-year deferred annuity-due 5|a_70 = 6,445
  d5 <- axn(women_5, x = 70, m = 5)
  expect_in_bracket(6.445, d5, d5 + up)
})

test_that("Destatis example 3.6 (man 55, woman 50, 5%): monthly single and joint annuities", {
  k12 <- 0.4664
  Dm55 <- 1e5 * Exn(men_5, x = 0, n = 55)
  Dw50 <- 1e5 * Exn(women_5, x = 0, n = 50)
  am <- axn(men_5, x = 55)
  aw <- axn(women_5, x = 50)
  expect_in_bracket(13.366, am - k12, am + tail_upper_5pc(men_1pc) / Dm55 - k12)
  expect_in_bracket(15.828, aw - k12, aw + tail_upper_5pc(women_1pc) / Dw50 - k12)
  # joint life: the tail beyond the man's age 100 is bounded by his own tail
  axy <- axyzn(list(men_5, women_5), x = c(55, 50), i = 0.05, status = "joint")
  expect_in_bracket(12.590, axy - k12, axy + tail_upper_5pc(men_1pc) / Dm55 - k12)
})
