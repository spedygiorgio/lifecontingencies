# Source: Statistisches Bundesamt (Destatis), "Kommutationszahlen und
# Versicherungsbarwerte fuer Leibrenten 2002/2004", Wiesbaden, April 2006.
# https://www.statistischebibliothek.de/mir/servlets/MCRFileNodeServlet/DEHeft_derivate_00012557/5126201049004.pdf
# Period life table Germany 2002/2004 (Sterbetafel), men and women, radix
# 100,000 at age 0. The publication prints for each age 0-100 the columns
# lx, Dx, Nx, annuity-due a_x and monthly annuity-due a_x^(12) at 1% (and
# other rates), plus worked examples at 5% in its methodological section.
#
# How the published table is used here:
# - lx is printed as an integer while Dx has three decimals, so the table is
#   rebuilt from lx = Dx * 1.01^x (the printed lx agree within 0.5);
# - the published Nx include ages beyond 100, which are not printed. The
#   tail N_101 = N_100 - D_100 is a published quantity at 1%, so at 1% the
#   whole life annuity is a_x = (sum up to 100) + N_101 / D_x;
# - at 5% the tail is not printed: tail-free example values are checked
#   exactly, whole life values are checked against a rigorous bracket
#   [value up to age 100, value plus an upper bound of the tail], where
#   sum_(y>=101) l_y 1.05^-y <= (1.01/1.05)^101 * N_101(1%);
# - the monthly values use the publication's deduction a^(12) = a - k(12)
#   with the printed k(12) = 0.4664 at 5%.

