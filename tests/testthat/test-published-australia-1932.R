au_act <- new("actuarialtable", x = au_males$x, lx = au_males$lx,
              interest = 0.03, name = "Australian males 1932-34 (3%)")
ocr_garbled <- c(32, 36, 38, 39, 43)
pub <- au_males_3pc[!au_males_3pc$x %in% ocr_garbled, ]

test_that("Australia 1932-34: lx and dx are consistent", {
  n <- nrow(au_males)
  expect_equal(au_males$lx[-n] - au_males$dx[-n], au_males$lx[-1])
})

test_that("Australia 1932-34 at 3%: Dx and Nx reproduced", {
  D_pkg <- 1e5 * Exn(au_act, x = 0, n = pub$x)
  expect_lte(max(abs(D_pkg - pub$Dx)), 0.8)
  N_pkg <- axn(au_act, x = pub$x) * D_pkg
  expect_lte(max(abs(N_pkg - pub$Nx)), 3)
})

test_that("Australia 1932-34 at 3%: annuity a_x, assurance A_x and premium P_x", {
  a_pkg <- axn(au_act, x = pub$x, payment = "immediate")
  expect_lte(max(abs(a_pkg - pub$ax)), 0.001)
  A_pkg <- Axn(au_act, x = pub$x)
  expect_lte(max(abs(A_pkg - pub$Ax)), 1e-4)
  P_pkg <- A_pkg / axn(au_act, x = pub$x)
  expect_lte(max(abs(P_pkg - pub$Px)), 1.5e-5)
})
