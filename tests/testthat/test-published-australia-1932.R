#   Dx is compared within 0.8, Nx within 3, a_x within 0.001, A_x within
#   1e-4 and P_x within 1.5e-5.
# - the printed annuity column is the annuity-immediate a_x = N_(x+1)/D_x;
#   P_x = M_x / N_x is the annual premium for a whole life assurance.
# - the scanned tables were transcribed from the OCR text layer; ages 32,
#   36, 38, 39 and 43 contain cells that the text layer garbles (for example
