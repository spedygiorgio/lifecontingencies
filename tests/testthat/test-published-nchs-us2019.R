## Published worked example: complete US period life tables 2019 (NCHS).
##
## Source: Arias E., Xu J. (2022). "United States Life Tables, 2019".
##   National Vital Statistics Reports, vol. 70, no. 19. Hyattsville, MD:
##   National Center for Health Statistics. Table 1 (total population) and
##   Table 2 (males): single-year ages 0..100+, columns qx, lx, dx, Lx, Tx, ex.
##   https://www.cdc.gov/nchs/data/nvsr/nvsr70/nvsr70-19.pdf
##   (These tables are the standard reference of US demography courses.)
##
## The published columns are rounded (lx, dx, Lx, Tx to integers, qx to 6 digits,
## ex to 1 decimal), so every comparison below uses a tolerance that reflects
## that rounding. The tables were transcribed and checked for internal
## consistency (dx = lx - lx+1, Tx = sum of Lx up to rounding, ex = Tx/lx).
##
## Convention differences between NCHS and lifecontingencies, documented here:
##  * Lxt() uses Lx = lx - fxt * dx with fxt = 0.5 by default. NCHS uses a_x = 0.5
##    for x >= 1 (so Lx matches to rounding) but a_0 ~ 0.126-0.128 (separation
##    factor of infants), so L0 matches only with fxt = 1 - a0.
##  * The last interval 100+ is closed by NCHS with L100 = l100 / m100 (open
##    interval), whereas Tx() closes it with l_omega / 2 (omega = 100). Hence
##    Tx_package(x) + (L100_published - l100 / 2) = Tx_published(x) up to rounding.

