nchs_tables <- list(total = nchs_total, male = nchs_male)

nchs_lifetable <- function(d, name) {
  new("lifetable", x = d$age, lx = d$lx, name = name)
}

for (nm in names(nchs_tables)) {
  local({
    d <- nchs_tables[[nm]]
    lt <- nchs_lifetable(d, paste("US 2019", nm))
    omega <- 100
    ages <- 0:99
    tail_gap <- d$Lx[101] - d$lx[101] / 2   # NCHS open-interval L100 vs package l_omega/2

    test_that(paste("US 2019", nm, ": table structure and radix"), {
      expect_equal(getOmega(lt), omega)
      expect_equal(lt@lx[1], 100000)
      expect_equal(length(lt@x), 101)
    })

    test_that(paste("US 2019", nm, ": dxt reproduces published dx"), {
      dx <- sapply(ages, function(a) dxt(lt, a))
      expect_true(max(abs(dx - d$dx[1:100])) <= 1)  # integer rounding of both columns
    })

    test_that(paste("US 2019", nm, ": qxt/pxt reproduce published qx and px"), {
      qx <- sapply(0:89, function(a) qxt(lt, a, 1))
      px <- sapply(0:89, function(a) pxt(lt, a, 1))
      expect_true(max(abs(qx - d$qx[1:90])) < 5e-5)
      expect_equal(px, 1 - qx, tolerance = 1e-12)
      # multi-year survival is the ratio of lx
      expect_equal(pxt(lt, 20, 40), d$lx[61] / d$lx[21], tolerance = 1e-12)
      expect_equal(pxt(lt, 65, 25), d$lx[91] / d$lx[66], tolerance = 1e-12)
      # 20|10 q40 = (l60 - l70)/l40 from the published lx column
      expect_equal(pxt(lt, 40, 20) * qxt(lt, 60, 10),
                   (d$lx[61] - d$lx[71]) / d$lx[41], tolerance = 1e-12)
    })

    test_that(paste("US 2019", nm, ": Lxt reproduces published Lx (ages >= 1)"), {
      L <- sapply(1:99, function(a) Lxt(lt, a))
      expect_true(max(abs(L - d$Lx[2:100])) <= 1)
    })

    test_that(paste("US 2019", nm, ": Lxt age 0 depends on fxt (infant separation factor)"), {
      # package default (fxt = 0.5): L0 = l0 - 0.5 * d0
      expect_equal(Lxt(lt, 0), lt@lx[1] - 0.5 * (lt@lx[1] - lt@lx[2]), tolerance = 1e-12)
      # a0 implied by the published L0: L0 = l1 + a0 * d0  (approx. 0.13 in 2019)
      a0 <- (d$Lx[1] - d$lx[2]) / (d$lx[1] - d$lx[2])
      expect_true(a0 > 0.10 && a0 < 0.15)
      # Lxt uses fxt as the fraction of the year lived by those who die: fxt = 1 - a0
      expect_true(abs(Lxt(lt, 0, fxt = 1 - a0) - d$Lx[1]) <= 1)
    })

    test_that(paste("US 2019", nm, ": mxt = dx / Lx and matches published ratio"), {
      expect_equal(mxt(lt, 40, 1), dxt(lt, 40, 1) / Lxt(lt, 40, 1), tolerance = 1e-12)
      m <- sapply(1:90, function(a) mxt(lt, a, 1))
      expect_equal(m, d$dx[2:91] / d$Lx[2:91], tolerance = 2e-3)
    })

    # tolerance 8: published Tx accumulates unrounded Lx, so it drifts a few units from sum(rounded Lx)
    test_that(paste("US 2019", nm, ": Tx matches published Tx up to the open-interval convention"), {
      for (a in c(1, 5, 20, 40, 65, 80, 90, 99)) {
        expect_true(abs(Tx(lt, a) + tail_gap - d$Tx[a + 1]) <= 8,
                    info = paste("age", a))
      }
      # Tx(0) additionally differs by the age-0 separation factor
      gap0 <- d$Lx[1] - (d$lx[1] - 0.5 * d$dx[1])
      expect_true(abs(Tx(lt, 0) + tail_gap + gap0 - d$Tx[1]) <= 8)
      # differences of Tx give one-year Lx
      expect_equal(Tx(lt, 30) - Tx(lt, 31), Lxt(lt, 30), tolerance = 1e-9)
    })

    test_that(paste("US 2019", nm, ": complete life expectancy vs published ex"), {
      for (a in c(1, 20, 40, 65, 80, 90)) {
        exPkg <- exn(lt, a, type = "complete")
        expect_equal(exPkg, Tx(lt, a) / lt@lx[a + 1], tolerance = 1e-10)
        # correct for the open-interval convention, then compare to the 1-decimal ex
        expect_true(abs(exPkg + tail_gap / d$lx[a + 1] - d$ex[a + 1]) <= 0.051,
                    info = paste("age", a))
      }
    })

    test_that(paste("US 2019", nm, ": curtate expectation equals direct sum of published lx"), {
      for (a in c(0, 25, 50, 75)) {
        direct <- sum(d$lx[(a + 2):101]) / d$lx[a + 1]
        expect_equal(exn(lt, a, type = "curtate"), direct, tolerance = 1e-10)
      }
    })

    test_that(paste("US 2019", nm, ": probs2lifetable rebuilds lx from published qx"), {
      rebuilt <- probs2lifetable(probs = d$qx[1:100], radix = 100000, type = "qx",
                                 name = "rebuilt")
      expect_equal(rebuilt@lx[1], 100000)
      expect_equal(rebuilt@lx[1:96], d$lx[1:96], tolerance = 2e-4)  # qx rounded to 6 digits
    })
  })
}
